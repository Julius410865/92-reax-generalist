"""Generated task types (DEV-GUIDELINES.md section 3): registry and generator.

    python -I tools/gen_generalist.py                    # every task module in tools/gen/
    python -I tools/gen_generalist.py --tasks parental_leave,parking_fee [--out DIR]

Every task module in tools/gen/ (see tools/gen/base.py for the contract) is registered by its file name. Item i of a split
is drawn from random.Random(f"{GEN_VERSION}|{task}|{split}|{i}") (later attempts of an unusable draw: "...|{i}|{a}");
the gold comes from the module's solve(). Splits are generated test, select, train in that order and a rendered text
(normalised instructions of all questions) never repeats across them. Output: <out>/<task>.<split>.jsonl and
<out>/<task>.manifest.json (counts, option counts, gold position and yes shares, sha256 of every file). Deterministic:
the same GEN_VERSION gives byte-identical files.
"""

from __future__ import annotations

import argparse
import collections
import glob
import hashlib
import importlib
import json
import os
import random
import re
import sys

ROOT = os.path.abspath(os.path.dirname(os.path.dirname(__file__)))
sys.path.insert(0, ROOT)
from tools.gen import base as B  # noqa: E402

OUT = os.path.join(ROOT, "data", "generalist", "gen")
COUNTS = (("test", 150), ("select", 150), ("train", 3000))
MAX_ATTEMPTS = 20


def task_modules() -> dict[str, object]:
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "tools", "gen", "*.py"))):
        name = os.path.basename(p)[:-3]
        if name in ("__init__", "base") or name.startswith("_"):
            continue
        mod = importlib.import_module(f"tools.gen.{name}")
        if getattr(mod, "TASK", None) == name:
            out[name] = mod
    return out


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower()).strip()


def generate(mod, out_dir: str, counts=COUNTS) -> dict:
    from reax_subnet.spec import v5
    os.makedirs(out_dir, exist_ok=True)
    seen: set[str] = set()
    stats, files = {}, {}
    for split, n in counts:
        rows, i, retries, dups = [], 0, 0, 0
        while len(rows) < n:
            if i > 50 * n:
                raise SystemExit(f"{mod.TASK}/{split}: only {len(rows)} of {n} rows after {i} seeds")
            row = None
            for a in range(MAX_ATTEMPTS):
                rng = random.Random(f"{B.GEN_VERSION}|{mod.TASK}|{split}|{i}" + (f"|{a}" if a else ""))
                try:
                    case = mod.draw(rng)
                    answers = mod.solve(case)
                    row = B.make_row(mod, split, len(rows), mod.render(case, rng), answers, rng)
                    break
                except B.Retry:
                    retries += 1
            i += 1
            if row is None:
                continue
            key = norm(" || ".join(q["instructions"] for q in row["questions"]))
            if key in seen:
                dups += 1
                continue
            v5.validate_mirror_row(row)
            seen.add(key)
            rows.append(row)
        path = os.path.join(out_dir, f"{mod.TASK}.{split}.jsonl")
        with open(path, "w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")   # never sort_keys: it would reorder yes/no and >26 options
        files[os.path.basename(path)] = hashlib.sha256(open(path, "rb").read()).hexdigest()
        qs = [q for r in rows for q in r["questions"]]
        yes = [q for q in qs if set(q["criteria"]) == {"yes", "no"}]
        mcq = [q for q in qs if set(q["criteria"]) != {"yes", "no"}]
        stats[split] = {"rows": len(rows), "questions": len(qs), "seeds_used": i, "retries": retries, "duplicates_skipped": dups,
                        "options": dict(sorted(collections.Counter(len(q["criteria"]) for q in qs).items())),
                        "yes_share": round(sum(q["expected"] == "yes" for q in yes) / len(yes), 4) if yes else None,
                        "gold_position": dict(sorted(collections.Counter(list(q["criteria"]).index(q["expected"]) for q in mcq).items()))}
    manifest = {"task": mod.TASK, "part": mod.PART, "area": mod.AREA, "gold": mod.GOLD, "gen_version": B.GEN_VERSION,
                "module": f"tools/gen/{mod.TASK}.py",
                "module_sha256": hashlib.sha256(open(os.path.join(ROOT, "tools", "gen", f"{mod.TASK}.py"), "rb").read()).hexdigest(),
                "licence": {"name": "generated by code in this repository (no third-party data)", "url": None},
                "splits": stats, "files": files}
    with open(os.path.join(out_dir, f"{mod.TASK}.manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=1)
    return manifest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tasks", default=None, help="comma-separated task names (default: all)")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    mods = task_modules()
    names = [t for t in (a.tasks.split(",") if a.tasks else mods)]
    missing = [t for t in names if t not in mods]
    if missing:
        raise SystemExit(f"unknown tasks: {missing}; have {sorted(mods)}")
    for t in names:
        m = generate(mods[t], a.out)
        s = m["splits"]
        print(f"{t}: " + ", ".join(f"{k} {v['rows']}" for k, v in s.items())
              + f" | yes share {s['train']['yes_share']} | options {s['train']['options']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
